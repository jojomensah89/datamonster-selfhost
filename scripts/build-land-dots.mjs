// Samples a land mask into the dot grids the live map draws (src/dashboard/assets/land-dots.ts).
// Run once when the look of the dots should change; the output is committed, so builds need no network.
//
//   curl -sSLo ne_110m_land.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
//   node scripts/build-land-dots.mjs ne_110m_land.geojson
//
// Source: Natural Earth 1:110m land (public domain), see THIRD_PARTY_NOTICES.md. A coarse display mask, not a
// boundary authority.
//
// Two grids, run-length encoded per latitude row ("lat:start,len,start,len|..."):
// - GLOBE: equal-area-ish, the longitude step widens with 1/cos(lat), so the sphere's dots are evenly spaced.
// - FLAT: a regular 2° grid, so the flat map's dots line up in rows and columns.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-land-dots.mjs <ne_110m_land.geojson>');
  process.exit(1);
}
const geo = JSON.parse(readFileSync(src, 'utf8'));
const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (g.type === 'MultiPolygon') polys.push(...g.coordinates);
  else if (g.type === 'Polygon') polys.push(g.coordinates);
}
const inside = (x, y, ring) => {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [ax, ay] = ring[i];
    const [bx, by] = ring[j];
    if (ay > y !== by > y && x < ((bx - ax) * (y - ay)) / (by - ay) + ax) hit = !hit;
  }
  return hit;
};
const boxed = polys.map((p) => {
  const xs = p[0].map((a) => a[0]);
  const ys = p[0].map((a) => a[1]);
  return { p, x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
});
const isLand = (lon, lat) => boxed.some(({ p, x0, x1, y0, y1 }) => lon >= x0 && lon <= x1 && lat >= y0 && lat <= y1 && inside(lon, lat, p[0]) && !p.slice(1).some((h) => inside(lon, lat, h)));

/** One latitude row: the land cells of a row of `n` cells, as start,len runs. */
function row(lat, n) {
  const step = 360 / n;
  const runs = [];
  let start = -1;
  for (let i = 0; i <= n; i++) {
    const land = i < n && isLand(-180 + (i + 0.5) * step, lat);
    if (land && start < 0) start = i;
    if (!land && start >= 0) {
      runs.push(start, i - start);
      start = -1;
    }
  }
  return runs.length ? `${lat}:${n}:${runs.join(',')}` : '';
}

function grid(cells) {
  const rows = [];
  let count = 0;
  for (let lat = -56; lat <= 82; lat += 2) {
    const r = row(lat, cells(lat));
    if (!r) continue;
    rows.push(r);
    const runs = r.split(':')[2].split(',').map(Number);
    for (let i = 1; i < runs.length; i += 2) count += runs[i];
  }
  return { encoded: rows.join('|'), count };
}

const globe = grid((lat) => Math.max(45, Math.round(180 * Math.cos((lat * Math.PI) / 180))));
const flat = grid(() => 180);

const out = `// Generated by scripts/build-land-dots.mjs from Natural Earth 1:110m land (public domain). Do not edit by hand.
// Rows "lat:cells:start,len,...", run-length encoded; a cell's longitude is -180 + (i + 0.5) * 360 / cells.
// Globe: ${globe.count} dots, equal-area spacing. Flat: ${flat.count} dots on a regular 2° grid.
export const GLOBE_LAND = '${globe.encoded}';
export const FLAT_LAND = '${flat.encoded}';
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'dashboard', 'assets', 'land-dots.ts');
writeFileSync(dest, out);
console.log(`globe ${globe.count} dots, flat ${flat.count} dots, ${out.length} bytes -> ${dest}`);
